// Brand palette generator. Run: node hub/tools-palette.mjs
// Builds 11-step OKLCH scales with perceptually even lightness and the highest chroma sRGB allows at each step,
// then writes them into hub.css between the palette markers and prints a table for BRAND.md.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const L = { 50: 0.972, 100: 0.936, 200: 0.878, 300: 0.806, 400: 0.722, 500: 0.632, 600: 0.542, 700: 0.452, 800: 0.362, 900: 0.272, 950: 0.196 };

// hue: OKLCH hue at the light end and at the dark end (yellows drift toward amber as they darken so they stay vivid, not muddy)
// push: share of the gamut-maximum chroma to use; cap: absolute chroma ceiling (used by the neutral)
const SCALES = {
  violet: { hue: [292, 281], push: 0.96 },
  saffron: { hue: [98, 58], push: 0.97 },
  teal: { hue: [188, 196], push: 0.95 },
  coral: { hue: [12, 4], push: 0.95 },
  mint: { hue: [158, 164], push: 0.93 },
  neutral: { hue: [288, 284], push: 1, cap: l => (l > 0.6 ? 0.02 : 0.02 + (0.6 - l) * 0.135) }
};

const lin2srgb = c => (c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055);
export function oklch2rgb(l, c, h) {
  const a = c * Math.cos(h * Math.PI / 180), b = c * Math.sin(h * Math.PI / 180);
  const l_ = l + 0.3963377774 * a + 0.2158037573 * b, m_ = l - 0.1055613458 * a - 0.0638541728 * b, s_ = l - 0.0894841775 * a - 1.291485548 * b;
  const L3 = l_ ** 3, M3 = m_ ** 3, S3 = s_ ** 3;
  return [4.0767416621 * L3 - 3.3077115913 * M3 + 0.2309699292 * S3, -1.2684380046 * L3 + 2.6097574011 * M3 - 0.3413193965 * S3, -0.0041960863 * L3 - 0.7034186147 * M3 + 1.707614701 * S3];
}
const inGamut = rgb => rgb.every(v => v >= -0.0005 && v <= 1.0005);
function maxChroma(l, h) { let lo = 0, hi = 0.4; for (let i = 0; i < 24; i++) { const mid = (lo + hi) / 2; if (inGamut(oklch2rgb(l, mid, h))) lo = mid; else hi = mid; } return lo; }
const hex = rgb => '#' + rgb.map(v => Math.round(Math.min(1, Math.max(0, lin2srgb(v))) * 255).toString(16).padStart(2, '0')).join('');

export function build() {
  const out = {};
  for (const [name, s] of Object.entries(SCALES)) {
    out[name] = {};
    for (const step of STEPS) {
      const l = L[step], t = (0.972 - l) / (0.972 - 0.196), h = s.hue[0] + (s.hue[1] - s.hue[0]) * t;
      let c = maxChroma(l, h) * s.push;
      if (s.cap) c = Math.min(c, s.cap(l));
      out[name][step] = { l, c: Math.round(c * 1000) / 1000, h: Math.round(h * 10) / 10, hex: hex(oklch2rgb(l, c, h)) };
    }
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const pal = build(), dir = dirname(fileURLToPath(import.meta.url)), file = join(dir, 'hub.css');
  let css = '  /* generated by tools-palette.mjs: do not edit by hand */\n';
  for (const [name, steps] of Object.entries(pal)) css += '  ' + STEPS.map(s => `--${name}-${s}:${steps[s].hex};`).join(' ') + '\n';
  // two grounds below the scale for the dark theme: deep, saturated, never grey
  css += `  --night:${hex(oklch2rgb(0.158, 0.078, 284))}; --night-2:${hex(oklch2rgb(0.128, 0.066, 284))};\n`;
  const src = readFileSync(file, 'utf8'), a = src.indexOf('/* palette:start */'), b = src.indexOf('/* palette:end */');
  if (a < 0 || b < 0) throw new Error('palette markers not found in hub.css');
  writeFileSync(file, src.slice(0, a) + '/* palette:start */\n' + css + '  ' + src.slice(b));
  for (const [name, steps] of Object.entries(pal)) {
    console.log('\n' + name);
    for (const s of STEPS) console.log(`  ${String(s).padStart(3)}  ${steps[s].hex}  oklch(${(steps[s].l * 100).toFixed(1)}% ${steps[s].c.toFixed(3)} ${steps[s].h})`);
  }
}
